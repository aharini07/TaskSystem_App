package com.taskSystem.TaskSystemApp;

import com.taskSystem.TaskSystemApp.dto.TaskRequestDto;
import com.taskSystem.TaskSystemApp.dto.TaskResponse;
import com.taskSystem.TaskSystemApp.enums.Priority;
import com.taskSystem.TaskSystemApp.enums.Status;
import com.taskSystem.TaskSystemApp.model.Users;
import com.taskSystem.TaskSystemApp.repository.UserRepository;
import com.taskSystem.TaskSystemApp.service.TaskService;
import lombok.Builder;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.security.crypto.password.PasswordEncoder;

import java.time.LocalDate;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
@Builder
@SpringBootTest
class TaskSystemAppApplicationTests {

	@Autowired
	private TaskService taskService;

	@Autowired
	private UserRepository userRepository;

	@Autowired
	private PasswordEncoder passwordEncoder;

	@Test
	void testTaskCreationAndRetrieval() {
		// ─── ARRANGE ───
		// 1. Ensure a test user exists in the database
		String testUsername = "testuser_junit";
		if (userRepository.findByUsername(testUsername).isEmpty()) {
			Users newUser = new Users();
			newUser.setUsername(testUsername);
			newUser.setPassword(passwordEncoder.encode("password123"));
			userRepository.save(newUser);
		}

		// 2. Fetch the user
		Users user = userRepository.findByUsername(testUsername).orElseThrow();

		// 3. Create a Task Request
		TaskRequestDto request = new TaskRequestDto(
				"Complete API Challenge",
				"Write unit tests using @SpringBootTest",
				LocalDate.now().plusDays(2),
				Priority.HIGH,
				Status.PENDING,
				"Work",
				"Developer"
		);

		// ─── ACT ───
		// 4. Create the task
		TaskResponse createdTask = taskService.createTask(user, request);

		// ─── ASSERT ───
		// 5. Verify the task was created correctly
		assertNotNull(createdTask, "The created task should not be null");
		assertNotNull(createdTask.id(), "The task ID should be generated by the database");
		assertEquals("Complete API Challenge", createdTask.title(), "Title should match the request");
		assertEquals(Priority.HIGH, createdTask.priority(), "Priority should match the request");
		assertEquals("Work", createdTask.category(), "Category should match the request");

		// 6. Retrieve the task using the ID
		TaskResponse fetchedTask = taskService.getTaskById(createdTask.id(), user);

		assertNotNull(fetchedTask);
		assertEquals(createdTask.id(), fetchedTask.id(), "Fetched task ID should match the created task ID");

		// 7. Clean up
		taskService.deleteTask(createdTask.id(), user);
	}
}